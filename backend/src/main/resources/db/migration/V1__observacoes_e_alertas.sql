CREATE TABLE alerta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL,
    bairro VARCHAR(40) NOT NULL,
    contexto VARCHAR(16) NOT NULL,
    inicio TIMESTAMP WITH TIME ZONE NOT NULL,
    ultima TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX alerta_tipo_bairro_tempo ON alerta(tipo, bairro, contexto, ultima DESC);
CREATE INDEX alerta_atividade ON alerta(ultima DESC, id DESC);

CREATE TABLE observacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave VARCHAR(140) NOT NULL,
    assinatura VARCHAR(64) NOT NULL,
    alerta_id BIGINT REFERENCES alerta(id),
    tipo VARCHAR(20) NOT NULL,
    bairro VARCHAR(40) NOT NULL,
    origem VARCHAR(16) NOT NULL,
    fonte VARCHAR(96) NOT NULL,
    confianca VARCHAR(12) NOT NULL,
    motivo_confianca VARCHAR(220) NOT NULL,
    observado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    recebido_em TIMESTAMP WITH TIME ZONE NOT NULL,
    descricao VARCHAR(380) NOT NULL,
    impacto INT NOT NULL CHECK (impacto BETWEEN 0 AND 3),
    valor DECIMAL(12,3),
    unidade VARCHAR(12),
    referencia DECIMAL(12,3),
    referencia_em TIMESTAMP WITH TIME ZONE,
    CONSTRAINT observacao_chave UNIQUE(origem, chave)
);
CREATE INDEX observacao_alerta ON observacao(alerta_id, observado_em DESC, id DESC);
CREATE INDEX observacao_historico ON observacao(origem, observado_em DESC, id DESC);
